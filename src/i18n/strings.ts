export type Lang = 'vi' | 'en';
export const LANGS: readonly Lang[] = ['vi', 'en'];

export const STRINGS: Readonly<Record<Lang, Readonly<Record<StringKey, string>>>> = { vi, en };

export type TParams = Record<string, string | number>;

export function translate(lang: Lang, key: StringKey, params?: TParams): string {
  const template = STRINGS[lang][key] ?? STRINGS.vi[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m,
  );
}

export function isStringKey(key: string): key is StringKey {
  return key in vi;
}
